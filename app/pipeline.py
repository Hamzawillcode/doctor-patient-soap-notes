"""Asynchronous pipeline runner.

Each stage is one of the existing scripts (transcribe.py, diarize.py, ... generate_soap_note.py), started as a
child process with asyncio.create_subprocess_exec. While a child runs, `await proc.communicate()` hands control
back to the event loop, so the API keeps answering requests (status polling, uploads, edits).

Why child processes instead of importing the functions?
  * the scripts stay exactly as they are and can still be run by hand;
  * each stage's models (Whisper, pyannote, BioBERT, Qwen ~8 GB) are freed when its process exits;
  * a crash in one stage can't take the web server down.

Only ONE pipeline runs at a time (asyncio.Semaphore(1)): the models are too big to run several side by side on
a laptop. Other jobs wait with status "queued".
"""

import asyncio
import json
import sys
from pathlib import Path

from .database import Consultation, NoteVersion, SessionLocal

ROOT = Path(__file__).resolve().parent.parent      # project root: scripts and outputs/ live here
OUTPUTS = ROOT / "outputs"
LOGS = ROOT / "logs"

_one_at_a_time = asyncio.Semaphore(1)


def stages_for(source_type: str, input_path: str, stem: str) -> list[tuple[str, list[str]]]:
    """(stage name, script + arguments) in run order. Every script writes outputs/<stem>_*.json."""
    if source_type == "audio":
        return [
            ("speech-to-text", ["transcribe.py", input_path]),
            ("speaker diarization", ["diarize.py", input_path]),
            ("alignment", ["align.py", input_path]),
            ("role identification", ["identify_roles.py", input_path]),
            ("clinical NER", ["clinical_extraction.py", input_path]),
            ("SOAP facts", ["build_soap_facts.py", input_path]),
            ("SOAP note writing", ["generate_soap_note.py", input_path]),
        ]
    # A pasted transcript already has DOCTOR/PATIENT labels, so it skips the audio stages.
    return [
        ("clinical NER", ["clinical_extraction.py", "--transcript", input_path]),
        ("SOAP facts", ["build_soap_facts.py", "--entities", f"outputs/{stem}_clinical_entities.json"]),
        ("SOAP note writing", ["generate_soap_note.py", "--facts", f"outputs/{stem}_soap_facts.json"]),
    ]


# --- small synchronous DB helpers, run in a worker thread so they never block the event loop -------------

def _update(consultation_id: int, **fields) -> None:
    with SessionLocal() as db:
        c = db.get(Consultation, consultation_id)
        for k, v in fields.items():
            setattr(c, k, v)
        db.commit()


def _save_results(consultation_id: int, stem: str, source_type: str) -> None:
    read = lambda suffix: json.loads((OUTPUTS / f"{stem}{suffix}").read_text())
    entities = read("_clinical_entities.json")
    facts = read("_soap_facts.json")
    note = read("_soap_note.json")
    if source_type == "audio":
        transcript = read("_roles.json")["utterances"]
    else:
        # clinical_extraction.py stores the role (DOCTOR/PATIENT) under "speaker" for pasted transcripts
        transcript = [{"role": t["speaker"], "speaker": t["speaker_label"], "start": t["start"],
                       "end": t["end"], "text": t["text"]} for t in entities["conversation"]]
    with SessionLocal() as db:
        c = db.get(Consultation, consultation_id)
        c.transcript = transcript
        c.entities = entities["summary"]
        c.soap_facts = facts["facts"]
        c.generated_note = note["note"]
        c.grounding = note["grounding_check"]
        c.generation = {"language_model": note["language_model"], **note["generation"]}
        c.status, c.current_stage, c.error = "completed", None, None
        # Version 1 of the editable note is exactly what the language model wrote.
        db.add(NoteVersion(consultation=c, version=1, content=note["note"],
                           author=note["language_model"], comment="Generated by the pipeline"))
        db.commit()


# --- the background job -----------------------------------------------------------------------------------

async def run_pipeline(consultation_id: int, source_type: str, input_path: str) -> None:
    stem = Path(input_path).stem
    stages = stages_for(source_type, input_path, stem)
    LOGS.mkdir(exist_ok=True)
    log_path = LOGS / f"{stem}.log"

    async with _one_at_a_time:                      # waits here (status "queued") if another job is running
        try:
            with open(log_path, "w") as log:
                for i, (name, cmd) in enumerate(stages):
                    await asyncio.to_thread(_update, consultation_id, status="running",
                                            current_stage=name, stages_done=i)
                    log.write(f"\n===== {name}: python {' '.join(cmd)}\n")
                    log.flush()
                    proc = await asyncio.create_subprocess_exec(
                        sys.executable, *cmd, cwd=ROOT,
                        stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.STDOUT)
                    output, _ = await proc.communicate()        # non-blocking wait
                    text = output.decode(errors="replace")
                    log.write(text)
                    log.flush()
                    if proc.returncode != 0:
                        raise RuntimeError(f"Stage '{name}' failed (exit code {proc.returncode}):\n{text[-1500:]}")
            await asyncio.to_thread(_save_results, consultation_id, stem, source_type)
            await asyncio.to_thread(_update, consultation_id, stages_done=len(stages))
        except Exception as e:                          # store the failure so the UI can show it
            await asyncio.to_thread(_update, consultation_id, status="failed", error=str(e))


def mark_interrupted_jobs() -> None:
    """On server start, jobs left 'queued'/'running' by a previous process can never finish: mark them failed."""
    with SessionLocal() as db:
        for c in db.query(Consultation).filter(Consultation.status.in_(["queued", "running"])):
            c.status, c.error = "failed", "Server restarted before the pipeline finished. Upload again."
        db.commit()
